export const t = (): Strings => (getConfig().locale === 'en' ? en : es);
export const intlLocale = () => (getConfig().locale === 'en' ? 'en-US' : 'es-MX');

/** Display only: amounts are integers in minor units computed by the server. */
export function money(amount: number, currency: string) {
  const nf = new Intl.NumberFormat(intlLocale(), { style: 'currency', currency });
  const digits = nf.resolvedOptions().maximumFractionDigits ?? 2;
  return nf.format(amount / 10 ** digits);
}
